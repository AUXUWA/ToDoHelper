/**
 * @file word_ssp.c
 * @brief SSP-MMC review scheduler: the DHP memory model + the optimal-interval
 *        policy table (v1.15.0).
 *
 * Source: https://github.com/maimemo/SSP-MMC (MIT), the scheduler published at
 * KDD 2022 by MaiMemo. Two halves:
 *
 *  1. The **DHP model** (their model/dhp.py, model/utils.py and algo/main.cpp):
 *     each word carries a memory state `(h, d)` - half-life h in days and
 *     difficulty d. Recall probability after t days is `p = 2^(-t/h)`; each
 *     review updates h (and d += 2 on a lapse, capped at 18). The constants are
 *     theirs, fitted on 220M real review logs - do not retune them by hand.
 *
 *  2. The **policy table** below: their value iteration (algo/main.cpp) solves
 *     "which interval minimises total review cost" for every state on the
 *     half-life grid 1.05^(i-30) days, i in [0,151]. The table was generated by
 *     tools/gen_ssp_policy.py, a faithful port of their DP (same constants,
 *     same grid, same convergence criterion); it is ~5.5 KB of const data.
 *
 * Why embed the whole thing instead of keeping the old 2^level heuristic: the
 * runtime cost is one powf/expf chain plus a table lookup per review, the table
 * lives in flash, and the intervals come from real learner data instead of a
 * guess. The old level field stays in word_progress_t for display only.
 */

#include "word_ssp.h"

#include <math.h>

#define SSP_BASE        1.05f
#define SSP_MIN_INDEX  (-30)
#define SSP_INDEX_LEN   152

/* Generated by tools/gen_ssp_policy.py from the SSP-MMC value iteration.
 * The file carries the full declaration (grid: index i -> 1.05^(i-30) days). */
#include "word_ssp_policy.inc"

static float start_halflife(uint8_t difficulty)
{
    float p = 0.925f - 0.05f * difficulty;
    if (p < 0.025f) {
        p = 0.025f;
    }
    return -1.0f / log2f(p);
}

static int halflife_index(float halflife_days)
{
    if (halflife_days <= 0.0f) {
        halflife_days = 0.01f;
    }
    int index = (int)(logf(halflife_days) / logf(SSP_BASE) + 0.5f) - SSP_MIN_INDEX;
    if (index < 0) {
        index = 0;
    }
    if (index >= SSP_INDEX_LEN) {
        index = SSP_INDEX_LEN - 1;
    }
    return index;
}

void word_ssp_review(uint8_t *difficulty, float *halflife_days,
                     bool known, float elapsed_days)
{
    if (difficulty == NULL || halflife_days == NULL) {
        return;
    }
    if (*difficulty < WORD_SSP_D_MIN) {
        *difficulty = WORD_SSP_D_DEFAULT;
    }

    /* First ever review (or a state reset): seed from the difficulty alone. */
    if (*halflife_days <= 0.0f || elapsed_days <= 0.0f) {
        *halflife_days = start_halflife(*difficulty);
        if (!known) {
            *difficulty = (*difficulty + 2 > WORD_SSP_D_MAX)
                              ? WORD_SSP_D_MAX
                              : (uint8_t)(*difficulty + 2);
        }
        return;
    }

    if (elapsed_days > 365.0f) {
        elapsed_days = 365.0f;
    }

    /* Recall probability at review time; clamped so the lapse branch's
     * (1-p)^-0.227 cannot blow up on a degenerate interval. */
    float p = exp2f(-elapsed_days / *halflife_days);
    if (p < 0.02f) {
        p = 0.02f;
    }
    if (p > 0.98f) {
        p = 0.98f;
    }

    if (known) {
        *halflife_days *= 1.0f + expf(3.81f) * powf(*difficulty, -0.534f) *
                              powf(*halflife_days, -0.127f) * powf(1.0f - p, 0.97f);
    } else {
        *halflife_days = expf(-0.041f) * powf(*difficulty, -0.041f) *
                         powf(*halflife_days, 0.377f) * powf(1.0f - p, -0.227f);
        *difficulty = (*difficulty + 2 > WORD_SSP_D_MAX)
                          ? WORD_SSP_D_MAX
                          : (uint8_t)(*difficulty + 2);
    }

    if (*halflife_days < 0.01f) {
        *halflife_days = 0.01f;
    }
    if (*halflife_days > 400.0f) {
        *halflife_days = 400.0f;
    }
}

int32_t word_ssp_next_interval_days(uint8_t difficulty, float halflife_days)
{
    if (difficulty < WORD_SSP_D_MIN || difficulty > WORD_SSP_D_MAX) {
        difficulty = WORD_SSP_D_DEFAULT;
    }
    if (halflife_days <= 0.0f) {
        halflife_days = start_halflife(difficulty);
    }
    const int16_t days =
        ssp_policy[difficulty - WORD_SSP_D_MIN][halflife_index(halflife_days)];
    return (days > 0) ? days : 1;
}
